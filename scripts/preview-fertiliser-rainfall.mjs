// Isolated local preview. Reads supplied fixtures; writes only MappingTest_ database.
import fs from 'node:fs/promises';
import path from 'node:path';
import {createHash} from 'node:crypto';
import mongoose from '../apps/api/node_modules/mongoose/index.js';
import {createModels} from '../apps/api/src/model/index.js';
import {createApp} from '../apps/api/src/app.js';
import {wageId} from '../apps/api/src/service/wages.js';
import {createServer} from '../apps/web/node_modules/vite/dist/node/index.js';
const root=path.resolve(import.meta.dirname,'..');
const load=async p=>JSON.parse(await fs.readFile(path.join(root,p),'utf8'));
const [gis,production,wages,rainfall,oldRainfall,hts]=await Promise.all(['data/estates/oban-nigeria/gis-import.json','data/production/oban-production.json','data/wages/oban-wages-2025.json','data/rainfall/oban-rainfall-through-sep2026.json','data/rainfall/oban-rainfall.json','data/hts-analysis/oban.json'].map(load));
const estateId=gis.estateId,db='MappingTest_fertiliser_rainfall_20261015';
await mongoose.connect('mongodb://127.0.0.1:27018/'+db,{serverSelectionTimeoutMS:8000});
const models=createModels(mongoose,'Preview');
const seed=async(Model,rows)=>{if(rows.length)await Model.bulkWrite(rows.map(row=>({replaceOne:{filter:{_id:row._id},replacement:row,upsert:true}})));};
await seed(models.Estate,[{_id:estateId,name:'Oban Nigeria',location:'Nigeria',boundary:gis.boundary}]);
await seed(models.Block,gis.blocks);
await seed(models.ProductionName,production.names);
await seed(models.YearlyProduction,production.yearly);
await seed(models.Wage,wages.records.map(r=>({...r,_id:wageId(estateId,r),estateId})));
await seed(models.WageArea,wages.areas.map(a=>({...a,estateId,_id:'wa-'+createHash('sha256').update(JSON.stringify([estateId,a.year,a.mapBlockCode])).digest('hex').slice(0,40)})));
const rainRows=[...oldRainfall.records.filter(r=>r.year<2017).map(r=>({...r,sourceId:oldRainfall.sourceId,sourceName:oldRainfall.sourceName,sourceFile:oldRainfall.sourceFile})),...rainfall.records.map(r=>({...r,sourceId:rainfall.sourceId,sourceName:rainfall.sourceName,sourceFile:rainfall.sourceFile}))];
await seed(models.AnnualRainfall,rainRows.map(r=>({...r,_id:`preview-rain-${r.year}`,estateId,active:true})));
const dataDir=path.join(root,'data/fertiliser-rainfall-preview');
await fs.mkdir(path.join(dataDir,'hts-analysis'),{recursive:true});
await fs.writeFile(path.join(dataDir,'hts-analysis',estateId+'.json'),JSON.stringify(hts));
const app=await createApp({models,dataDir,origins:[],authMode:'development',apiPath:'/api',serveWeb:false});
const vite=await createServer({root:path.join(root,'apps/web'),server:{middlewareMode:true,hmr:false},appType:'mpa'});
app.use(vite.middlewares);
app.get('/',(_req,res)=>res.redirect('/fertiliser-preview.html'));
const server=app.listen(4198,'127.0.0.1',()=>console.log('Local chart preview: http://127.0.0.1:4198/fertiliser-preview.html'));
process.on('SIGTERM',async()=>{server.close();await vite.close();await mongoose.disconnect();process.exit(0);});
